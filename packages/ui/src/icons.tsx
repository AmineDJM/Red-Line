export type IconName = keyof typeof ICONS;

/** Icônes « pleines » (remplies en plus du trait). */
const FILLED = new Set<IconName>(['play', 'forward']);

export interface IconProps {
  name: IconName;
  /** Taille en pixels (défaut 18). */
  size?: number;
  strokeWidth?: number;
  className?: string;
  style?: CSSProperties;
  /** Texte alternatif : sans lui, l'icône est décorative (aria-hidden). */
  title?: string;
}

export function Icon({ name, size = 18, strokeWidth = 1.6, className, style, title }: IconProps) {
  const paths = ICONS[name];
  return (
    <svg
      className={className ? `rl-icon ${className}` : 'rl-icon'}
      style={style}
      width={size}
      height={size}
      viewBox="0 0 24 24"
      fill={FILLED.has(name) ? 'currentColor' : 'none'}
      stroke="currentColor"
      strokeWidth={strokeWidth}
      strokeLinecap="round"
      strokeLinejoin="round"
      role={title ? 'img' : undefined}
      aria-hidden={title ? undefined : true}
      aria-label={title}
    >
      {paths.map((d, i) => (
        <path key={i} d={d} />
      ))}
    </svg>
  );
}
